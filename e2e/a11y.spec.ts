test('shelf, add bottles and the wine card', async ({ page }) => {
  await signUp(page)
  await page.goto('/bottle/sample-red-1')
  await expect(page.getByRole('heading', { level: 1, name: 'Sample Red 1' })).toBeVisible()
  await audit(page, 'wine card before the quiz')

  await page.goto('/')
  await page.getByRole('link', { name: 'Start the quiz' }).click()
  await page.getByText('Red wine', { exact: true }).click()
  await page.getByRole('button', { name: 'Next' }).click()
  await page.getByText('Skim', { exact: true }).click()
  await page.getByRole('button', { name: 'Next' }).click()
  await page.getByRole('button', { name: 'Show me wines now' }).click()
  await expect(page.getByText(/^You /).first()).toBeVisible()

  await page.goto('/shelf')
  await expect(page.getByRole('heading', { name: 'Your shelf is empty' })).toBeVisible()
  await audit(page, 'empty shelf')
  await page.getByRole('link', { name: 'Add bottles' }).click()
  await expect(page.getByText('10 bottles')).toBeVisible()
  await audit(page, 'add bottles')
  await addBottle(page, 'red', 'Sample Red 1')
  await audit(page, 'add bottles with a message and results')
  await page.getByLabel('Search the catalog').fill('zzzz')
  await expect(page.getByText('No bottles match')).toBeVisible()
  await audit(page, 'add bottles, nothing found')
  await page.getByRole('link', { name: '← My shelf' }).click()
  await expect(page.getByText('1 bottle at home')).toBeVisible()
  await audit(page, 'shelf with a bottle')

  await page.getByRole('link', { name: 'Sample Red 1', exact: true }).click()
  await expect(page.getByText('A good bet')).toBeVisible()
  await audit(page, 'wine card: a good bet')
  await page.getByRole('list', { name: 'Flavors' }).getByRole('button').first().click()
  await page.getByRole('list', { name: 'Wine words' }).getByRole('button').first().click()
  for (const d of await page.locator('details > summary').all()) await d.click()
  await audit(page, 'wine card with a word and every "What’s this?" open')

  await page.goto('/bottle/sample-red-3') // right type, wrong body: somewhere in the middle
  await expect(page.getByText('Worth a try')).toBeVisible()
  await audit(page, 'wine card: worth a try')
  await page.goto('/bottle/sample-white-1') // a type they steer away from
  await expect(page.getByText('A stretch')).toBeVisible()
  await audit(page, 'wine card: a stretch')
  await page.goto('/bottle/sample-white-2')
  await expect(page.getByText(/A good bet|Worth a try|A stretch/).first()).toBeVisible()
  await audit(page, 'wine card: another bottle')
  await page.goto('/bottle/nope')
  await expect(page.getByRole('heading', { name: 'We couldn’t find that bottle' })).toBeVisible()
  await audit(page, 'bottle not found')
})

