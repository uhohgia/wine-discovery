test('rating screens: choices, the dislike decoder, the thank-you, and where the rating shows up', async ({ page }) => {
  await signUp(page)
  await quickQuiz(page)
  await page.goto('/shelf/add')
  await addBottle(page, 'light red', 'Sample Red 1')

  await page.goto('/bottle/sample-red-1')
  await expect(page.getByRole('heading', { name: 'Tried it?' })).toBeVisible()
  await audit(page, 'wine card with "Tried it?"')

  await page.getByRole('link', { name: 'Rate this bottle' }).click()
  await expect(page.getByRole('heading', { level: 1, name: 'How was Sample Red 1?' })).toBeVisible()
  await audit(page, 'rate: nothing picked yet')
  await page.getByRole('button', { name: 'Save my rating' }).click()
  await expect(page.getByRole('alert')).toBeVisible()
  await audit(page, 'rate: asking to pick one')
  await page.getByText('Not for me', { exact: true }).click()
  await expect(page.getByText('What didn’t you like?')).toBeVisible()
  await audit(page, 'rate: not for me, reasons showing')
  for (const r of ['Too sharp or sour', 'Too heavy', 'Didn’t like the flavor']) await page.getByText(r, { exact: true }).click()
  await audit(page, 'rate: reasons picked')
  await page.getByRole('button', { name: 'Save my rating' }).click()
  await expect(page.getByRole('heading', { name: /^Thanks for rating/ })).toBeVisible()
  await audit(page, 'rate: thank you with a warm confirmation')

  await page.goto('/bottle/sample-red-1')
  await expect(page.getByText(/You said:/)).toBeVisible()
  await audit(page, 'wine card showing your rating')
  await rateBottle(page, 'Loved it')
  await page.goto('/shelf')
  await expect(page.getByRole('listitem').first()).toContainText('Loved it')
  await audit(page, 'shelf with a rating')
  await page.goto('/profile')
  await expect(page.getByText('Based on 2 ratings, so more bottles will sharpen this.')).toBeVisible()
  await audit(page, 'taste profile after ratings')
  await page.goto('/bottle/nope/rate')
  await expect(page.getByRole('heading', { name: 'We couldn’t find that bottle' })).toBeVisible()
  await audit(page, 'rate: bottle not found')
})

