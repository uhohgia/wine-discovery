import type { Bottle } from './bottles'

const q = (v: string): string => `'${v.replace(/'/g, "''")}'`
const arr = (a: readonly string[]): string => (a.length ? `array[${a.map(q).join(', ')}]::text[]` : `'{}'::text[]`)
const num = (v: number | null): string => (v === null ? 'null' : String(v))

const COLUMNS = [
  'id', 'name', 'producer', 'vintage', 'type', 'price', 'body', 'sweetness', 'acidity', 'tannin', 'fruit_character',
  'fruit_notes', 'flower_notes', 'extras', 'pairings', 'occasions', 'serve_tip', 'talking_point', 'easy_to_like',
  'usually_sold_at', 'label_image_path', 'is_placeholder',
] as const

function row(b: Bottle): string {
  return `  (${[
    q(b.id), q(b.name), q(b.producer), num(b.vintage), q(b.type), num(b.price), q(b.body), q(b.sweetness), q(b.acidity),
    q(b.tannin), q(b.fruit_character), arr(b.fruit_notes), arr(b.flower_notes), arr(b.extras), arr(b.pairings),
    arr(b.occasions), q(b.serve_tip), q(b.talking_point), String(b.easy_to_like), arr(b.usually_sold_at),
    b.label_image_path === null ? 'null' : q(b.label_image_path), String(b.is_placeholder),
  ].join(', ')})`
}

/** An idempotent upsert of the whole catalog: safe to run again after editing bottles.json. */
export function bottlesToSql(bottles: readonly Bottle[]): string {
  const updates = COLUMNS.filter((c) => c !== 'id').map((c) => `${c} = excluded.${c}`).join(',\n  ')
  return [
    '-- Generated by `npm run bottles:sql` from src/data/bottles.json. Do not edit by hand.',
    `insert into public.wd_bottles (${COLUMNS.join(', ')}) values`,
    bottles.map(row).join(',\n'),
    `on conflict (id) do update set\n  ${updates};`,
    '',
  ].join('\n')
}
